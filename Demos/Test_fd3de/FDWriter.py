font = VeFont

def load_font(path):
    global font
    file = open(path)
    font = eval(file.read())


def draw_char(char, x, y, scale, color):
    global font
    for n in range(len(font[char])):
        FD.draw_line(
        (font[char][n][0][0] * (scale * (screen_x//scale_factor))) + x,
        (font[char][n][0][1] * (scale * (screen_x//scale_factor))) + y,
        (font[char][n][1][0] * (scale * (screen_x//scale_factor))) + x,
        (font[char][n][1][1] * (scale * (screen_x//scale_factor))) + y, color)



def update():
    FD.update()

def write(sentence, x, y, scale=4, color=FD.WHITE, passive=True):
    sentence = str(sentence)
    for n in range(len(sentence)):
        if sentence[n] != " ":
            if n == 0:
                draw_char(sentence[n], x-scale, y, scale, color)
            else:
                draw_char(sentence[n], x+(scale*5*n), y, scale, color)
        else:
            FD.draw_line(x+(scale*5*n), y, x+(scale*5*n)+scale, y, FD.BLACK)

